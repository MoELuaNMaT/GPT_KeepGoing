def normalize(code):
    """把语言代码归一。未知代码退回默认语言。"""
    if not code:
        return DEFAULT_LANG
    if code in STRINGS:
        return code
    base = str(code).replace("_", "-").split("-")[0].lower()
    for known in LANG_ORDER:
        if known.split("-")[0].lower() == base:
            return known
    return DEFAULT_LANG


def t(lang, key, **kwargs):
    """取一条文案。缺键时回退默认语言，再回退键名本身。"""
    code = normalize(lang)
    table = STRINGS.get(code) or STRINGS[DEFAULT_LANG]
    text = table.get(key)
    if text is None:
        text = STRINGS[DEFAULT_LANG].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError):
            return text
    return text


def continue_text(lang):
    """该语言下发给对话的继续用语。"""
    return t(lang, "cont")


def native_name(code):
    return LANG_NATIVE.get(normalize(code), code)
